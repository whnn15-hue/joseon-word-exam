// 같은 묶음 안에서는 순서와 상관없이, 서로 다른 답이어야 정답 (21~23)
export const GROUPS = [[21, 22, 23]];

export const norm = (s) => String(s ?? "").replace(/[\s「」『』“”"'.,()\[\]·!?~\-]/g, "").toLowerCase();

export function grade(vals) {
  const marks = ANSWERS.map(() => false);
  const inGroup = new Set(GROUPS.flat());
  ANSWERS.forEach((a, i) => {
    if (inGroup.has(i + 1)) return;
    const v = norm(vals[i]);
    marks[i] = !!v && a.split("|").map(norm).includes(v);
  });
  GROUPS.forEach((g) => {
    const used = new Set();
    g.forEach((n) => {
      const v = norm(vals[n - 1]);
      const ok = !!v && ANSWERS[n - 1].split("|").map(norm).includes(v) && !used.has(v);
      if (ok) used.add(v);
      marks[n - 1] = ok;
    });
  });
  return marks;
}
